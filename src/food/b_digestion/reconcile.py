"""Reconcile measured LC-MS/MS peptides with theoretical digestion candidates.

Measured rows need ``sequence``; ``accession``, ``sample``, ``intensity`` and ``condition`` are optional. They are
matched to the theoretical peptides by exact sequence. Statuses:

* MATCHED_THEORETICAL     - predicted by the run; evidence_class becomes OBSERVED.
* OBSERVED_NOT_PREDICTED  - lies inside a substrate but the enzyme rules, length or
                            missed-cleavage limits did not generate it (rule gap, other
                            protease activity, or in-source fragmentation).
* NOT_IN_LIBRARY          - no substrate contains it.
* INVALID_SEQUENCE        - empty or non-standard residues.

I/L are isobaric in MS, so a measured sequence is also matched with I/L collapsed and
flagged ``il_ambiguous``. Observation is not quantitation: it says nothing about dose
or exposure.
"""
from __future__ import annotations

import csv
from pathlib import Path
from typing import Mapping, Sequence

from food.a_proteins.fasta import STANDARD, Substrate


def _il(s: str) -> str:
    return s.replace("I", "L")


def read_measured_csv(path: str | Path) -> list[dict]:
    """Rows of a measured-peptide CSV; refuses a file with no ``sequence`` column."""
    with open(path, newline="", encoding="utf-8") as fh:
        rd = csv.DictReader(fh)
        if "sequence" not in (rd.fieldnames or []):
            raise ValueError(f"{path}: required column 'sequence' is missing "
                             f"(found {rd.fieldnames}); rename your peptide column to 'sequence'")
        return list(rd)


def reconcile(theoretical: Sequence[Mapping], substrates: Sequence[Substrate], measured: Sequence[Mapping]) -> list[dict]:
    """One result row per measured peptide. ``theoretical`` is the peptide rows from `engine.run`."""
    theo = {r["sequence"]: r for r in theoretical}
    theo_il: dict[str, list[str]] = {}
    for s in theo:
        theo_il.setdefault(_il(s), []).append(s)

    out = []
    for r in measured:
        seq = (r.get("sequence") or "").strip().upper()
        base = {"sequence": seq, "accession_reported": r.get("accession", ""),
                "sample": r.get("sample", ""), "intensity": r.get("intensity", ""),
                "condition": r.get("condition", "")}
        if not seq or set(seq) - STANDARD:
            out.append({**base, "status": "INVALID_SEQUENCE", "peptide_id": "", "il_ambiguous": "",
                        "evidence_class": "",
                        "note": "empty or non-standard residues; keep only the 20 standard letters in "
                                "'sequence' and put modifications in a separate column"})
            continue
        if seq in theo:
            out.append({**base, "status": "MATCHED_THEORETICAL", "peptide_id": theo[seq]["peptide_id"],
                        "il_ambiguous": False, "evidence_class": "OBSERVED",
                        "note": f"parents: {theo[seq]['parent_substrates']}"})
            continue
        alt = theo_il.get(_il(seq))
        if alt:
            out.append({**base, "status": "MATCHED_THEORETICAL", "peptide_id": theo[alt[0]]["peptide_id"],
                        "il_ambiguous": True, "evidence_class": "OBSERVED",
                        "note": f"matches {alt[0]} only after treating I=L"})
            continue
        hosts = [s.substrate_id for s in substrates if seq in s.sequence]
        if hosts:
            out.append({**base, "status": "OBSERVED_NOT_PREDICTED", "peptide_id": "", "il_ambiguous": "",
                        "evidence_class": "OBSERVED",
                        "note": f"inside {len(hosts)} substrate(s), e.g. {hosts[0]}; not generated by the "
                                "run settings. Check enzyme rules, max_length, max_missed_cleavages"})
        else:
            out.append({**base, "status": "NOT_IN_LIBRARY", "peptide_id": "", "il_ambiguous": "",
                        "evidence_class": "", "note": "no digestion substrate contains this sequence"})
    return out
